
/* 
1. Write a Java program to declare variables of int, float, double, and char
data types, assign suitable values, and display all the values. 
*/


public class DataTypes {
    public static void main(String[] args) {
        int num1 = 1234;
        float num2 = 123.123456f;
        double num3 = 123.12345678911;
        char ch = 'A';

        System.out.println("num1 : " +num1);
        System.out.println("num2 : " +num2);
        System.out.println("num3 : " +num3);
        System.out.println("num5 : " +ch);
    }    
}