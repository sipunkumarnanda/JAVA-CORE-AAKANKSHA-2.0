/*
8. Write a Java program to declare an int variable and a double variable, assign suitable values, 
add them together, and display the result. Observe the data type of the result.
*/

public class ObserveDataTypes {
    public static void main(String[] args) {
        int val1 = 12345;
        double val2 = 12345.12345;
        System.out.println(val1 +" + "+ val2 +" = "+ (val1 + val2)); // Data Type Of Result is Double 
    }
}
